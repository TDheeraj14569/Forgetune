std::string CodeGenerator::generate(const IRGraph& graph) const {
    std::ostringstream oss;

    emit_headers(oss);
    emit_constants(oss, graph);
    emit_arena_pool(oss);
    emit_kernel_functions(oss, graph);
    emit_entry_point(oss, graph);

    return oss.str();
}

